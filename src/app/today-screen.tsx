"use client";

import { useLiveQuery } from "dexie-react-hooks";
import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { AskGainpath } from "@/components/ask-gainpath";
import { CelebrationCard, SegmentedProgress } from "@/components/celebration-card";
import { ExerciseSummary } from "@/components/exercise-summary";
import { PlayIcon, SparkIcon } from "@/components/icons";
import { Button, Notice, Section, primaryLinkClass } from "@/components/ui";
import { WhySheet } from "@/components/why-sheet";
import { getProfile, localDate } from "@/data/actions";
import { getDB } from "@/data/db";
import { repo } from "@/data/repo";
import { endDeloadWeek, generateSession, readLive, startDeloadWeek } from "@/data/sessions";
import { explain } from "@/engine/explain";
import { useSessionCelebration } from "@/hooks/use-celebration";
import { useProfile } from "@/hooks/use-data";
import { useSyncStatus } from "@/hooks/use-sync-status";
import { useTodaySession, useTrainingContext } from "@/hooks/use-training";
import { useAiStatus } from "@/lib/ai-client";
import { coachNote, firstNameFromEmail, greeting, readinessTitle } from "@/lib/coach";
import { CheckinCard } from "./checkin-card";

/** Wall clock for the greeting (read once per mount, outside render). */
const hourNow = () => new Date().getHours();

export function TodayScreen() {
  const profile = useProfile();
  const router = useRouter();
  const ctx = useTrainingContext();
  const session = useTodaySession();
  const sync = useSyncStatus();
  const sleepHours = useLiveQuery(
    async () =>
      (await repo("checkins").list()).find((c) => c.date === localDate())?.sleep_hours ?? null,
    [],
  );
  const celebration = useSessionCelebration(session, ctx);
  const [why, setWhy] = useState(false);
  const [asking, setAsking] = useState(false);
  const ai = useAiStatus();
  const [skipCheckin, setSkipCheckin] = useState(false);
  const [busy, setBusy] = useState(false);
  const [dismissedDeload, setDismissedDeload] = useState(false);
  const [hour] = useState(hourNow);
  const autoGenerated = useRef(false);

  useEffect(() => {
    if (profile !== null) return;
    // Next keeps visited routes alive (Activity), so `profile` may be stale from an
    // earlier visit; confirm against the database before redirecting.
    let cancelled = false;
    void getProfile().then((fresh) => {
      if (!fresh && !cancelled) router.replace("/onboarding");
    });
    return () => {
      cancelled = true;
    };
  }, [profile, router]);

  const checkedIn = ctx?.hasCheckin || skipCheckin;
  // Build today's session as soon as the check-in is done (or skipped).
  useEffect(() => {
    if (!ctx || session !== null || !checkedIn || autoGenerated.current) return;
    autoGenerated.current = true;
    void generateSession(getDB());
  }, [ctx, session, checkedIn]);

  const name = firstNameFromEmail(sync.email);
  const header = (
    <header className="flex items-center justify-between gap-3 px-1">
      <div className="flex min-w-0 flex-col">
        <span className="text-sm text-on-surface-variant">
          {new Date().toLocaleDateString(undefined, {
            weekday: "long",
            day: "numeric",
            month: "long",
          })}
        </span>
        <h1 className="truncate">
          {greeting(hour)}
          {name ? `, ${name}` : ""}
        </h1>
      </div>
      {name && (
        <Link
          href="/settings"
          aria-label="Settings"
          className="flex h-12 w-12 shrink-0 items-center justify-center rounded-full bg-primary-container text-lg font-semibold text-on-primary-container"
        >
          {name.charAt(0)}
        </Link>
      )}
    </header>
  );

  if (profile === undefined || ctx === undefined || session === undefined) {
    return (
      <div className="flex flex-col gap-4">
        {header}
        <p className="px-1 text-on-surface-variant">Loading…</p>
      </div>
    );
  }
  if (!profile || !ctx) {
    return (
      <div className="flex flex-col gap-4">
        {header}
        <Notice>Register your gym to get a session.</Notice>
        <Link href="/gym" className={primaryLinkClass}>
          My gym
        </Link>
      </div>
    );
  }

  const live = session ? readLive(session) : null;
  const regenerate = async () => {
    setBusy(true);
    await generateSession(getDB());
    setBusy(false);
  };
  const { readiness, deload, week } = ctx;
  const done = session?.status === "done";
  const sessionNo = week.completed + 1;
  const weekLine =
    sessionNo > week.plannedSessions
      ? `Extra session: ${week.plannedSessions} planned this week`
      : done
        ? `${sessionNo} of ${week.plannedSessions} sessions done this week`
        : `Session ${sessionNo} of ${week.plannedSessions} this week`;
  const visible = live?.exercises.filter((e) => e.status !== "swapped_out") ?? [];
  // Von Restorff: one highlighted anchor, the same one the coach note names.
  const leadAnchor = visible.find((e) => e.isAnchor);
  const canStart = !!live && !done && visible.length > 0;

  return (
    <div className="flex flex-col gap-4">
      {header}

      {!checkedIn && (
        <>
          <CheckinCard onDone={() => (autoGenerated.current = false)} />
          <button
            type="button"
            className="min-h-12 self-center rounded-full px-4 text-sm font-semibold text-primary hover:bg-primary/8"
            onClick={() => setSkipCheckin(true)}
          >
            Skip check-in today
          </button>
        </>
      )}

      {checkedIn && done && celebration && (
        <CelebrationCard label="Session done" celebration={celebration}>
          <SegmentedProgress
            done={Math.min(sessionNo, week.plannedSessions)}
            total={week.plannedSessions}
            label={weekLine}
          />
        </CelebrationCard>
      )}

      {checkedIn && (
        <section
          aria-label="Coach"
          className="flex flex-col gap-3 rounded-card bg-primary-container p-[18px] text-on-primary-container"
        >
          <div className="flex items-center gap-3.5">
            <ReadinessRing score={ctx.hasCheckin ? readiness.score : null} />
            <div className="flex min-w-0 flex-col gap-0.5">
              <span className="text-title">
                {ctx.hasCheckin ? readinessTitle(readiness.band) : "No check-in today"}
              </span>
              <span className="text-[13px] opacity-85">{weekLine}</span>
            </div>
          </div>
          <p className="text-[15px] leading-[1.45]">
            {coachNote({
              readiness,
              hasCheckin: ctx.hasCheckin,
              sleepHours: sleepHours ?? null,
              live,
              catalog: ctx.catalog,
            })}
          </p>
          {!done && (
            <SegmentedProgress
              done={week.completed}
              total={week.plannedSessions}
              tone="primary"
              label={weekLine}
            />
          )}
        </section>
      )}

      {deload.active ? (
        <Notice>
          Lighter week in progress: same exercises, fewer sets, more in reserve (DELOAD-2).{" "}
          <button
            type="button"
            className="font-semibold text-primary underline underline-offset-4"
            onClick={() => void endDeloadWeek(getDB())}
          >
            End early
          </button>
        </Notice>
      ) : (
        (deload.check.trigger || deload.check.reminder) &&
        !dismissedDeload && (
          <Section title={deload.check.trigger ? "A lighter week may help" : "Lighter week?"}>
            {deload.check.rationale.map((r) => (
              <p key={r.rule} className="text-sm">
                {explain(r)}
              </p>
            ))}
            <p className="text-xs text-on-surface-variant">
              A deload reduces sets and effort but keeps you training: a full week off isn&apos;t
              better (DELOAD-2).
            </p>
            <div className="flex gap-2">
              <Button
                variant="tonal"
                onClick={async () => {
                  await startDeloadWeek(getDB());
                  if (!live?.startedAt) await regenerate();
                }}
              >
                Start lighter week
              </Button>
              <Button variant="text" onClick={() => setDismissedDeload(true)}>
                Not now
              </Button>
            </div>
          </Section>
        )
      )}

      {checkedIn && !live && (
        <Section title="Today's path">
          <p className="text-sm text-on-surface-variant">Building your session…</p>
          <Button variant="tonal" disabled={busy} onClick={regenerate}>
            Build session
          </Button>
        </Section>
      )}

      {live && session && (
        <section
          aria-labelledby="path-title"
          className="flex flex-col rounded-card bg-surface-container-low py-2"
        >
          <div className="flex items-baseline justify-between gap-3 px-4 pt-2.5 pb-1.5">
            <h2 id="path-title" className="text-title">
              {done
                ? "Done for today"
                : live.meta.isDeload
                  ? "Today's path (lighter)"
                  : "Today's path"}
            </h2>
            <span className="truncate text-[13px] text-on-surface-variant">
              {visible.length} exercise{visible.length === 1 ? "" : "s"} · {ctx.gym.name}
            </span>
          </div>
          {live.exercises.length === 0 && (
            <div className="px-4 py-2">
              <Notice>
                Nothing to program: register equipment with linked exercises in My gym.
              </Notice>
            </div>
          )}
          <ul className="flex flex-col">
            {visible.map((e) => (
              <li key={`${e.exerciseId}-${e.replaces ?? ""}`} className="px-4 py-2">
                <ExerciseSummary
                  e={e}
                  exercise={ctx.catalog.get(e.exerciseId)}
                  equipment={ctx.equipmentById}
                  lead={e === leadAnchor}
                  compact
                />
              </li>
            ))}
          </ul>
          {(session.status === "planned" || done) && (
            <div className="flex flex-wrap gap-1 px-2 pt-1">
              {session.status === "planned" && (
                <button
                  type="button"
                  disabled={busy}
                  onClick={regenerate}
                  className="min-h-10 rounded-full px-3 text-sm font-semibold text-primary hover:bg-primary/8 disabled:opacity-40"
                >
                  Rebuild session
                </button>
              )}
              {done && (
                <button
                  type="button"
                  onClick={() => setWhy(true)}
                  className="min-h-10 rounded-full px-3 text-sm font-semibold text-primary hover:bg-primary/8"
                >
                  Why does today look like this?
                </button>
              )}
            </div>
          )}
        </section>
      )}

      {ai?.enabled && (
        <Button variant="tonal" onClick={() => setAsking(true)}>
          <SparkIcon size={18} />
          Ask Gainpath
        </Button>
      )}

      {canStart && (
        // Thumb zone (Fitts): the one primary action sits at the bottom, above the nav bar.
        <div className="sticky bottom-[calc(5rem+env(safe-area-inset-bottom))] z-10 -mx-4 mt-auto flex gap-2 bg-gradient-to-t from-surface from-75% to-transparent px-4 pt-4 pb-3">
          <Link href="/session" className={`${primaryLinkClass} min-h-16 flex-1 shadow-sm`}>
            <PlayIcon size={20} />
            {session!.status === "active" ? "Continue session" : "Start session"}
          </Link>
          <button
            type="button"
            onClick={() => setWhy(true)}
            aria-label="Why does today look like this?"
            title="Why does today look like this?"
            className="flex min-h-16 w-16 shrink-0 items-center justify-center rounded-[20px] bg-secondary-container text-xl font-extrabold text-on-secondary-container"
          >
            ?
          </button>
        </div>
      )}

      {why && live && <WhySheet live={live} catalog={ctx.catalog} onClose={() => setWhy(false)} />}
      {asking && <AskGainpath onClose={() => setAsking(false)} />}
    </div>
  );
}

/** Readiness score as a ring (score/100); "–" without a check-in. */
function ReadinessRing({ score }: { score: number | null }) {
  const r = 25;
  const c = 2 * Math.PI * r;
  const filled = score === null ? 0 : (Math.max(0, Math.min(100, score)) / 100) * c;
  return (
    <div className="relative h-[60px] w-[60px] shrink-0">
      <svg
        width="60"
        height="60"
        viewBox="0 0 60 60"
        role="img"
        aria-label={score === null ? "Readiness unknown" : `Readiness ${score} of 100`}
      >
        <circle
          cx="30"
          cy="30"
          r={r}
          fill="none"
          stroke="currentColor"
          strokeOpacity={0.16}
          strokeWidth="7"
        />
        {score !== null && score > 0 && (
          <circle
            cx="30"
            cy="30"
            r={r}
            fill="none"
            className="stroke-primary"
            strokeWidth="7"
            strokeLinecap="round"
            strokeDasharray={`${filled} ${c}`}
            transform="rotate(-90 30 30)"
          />
        )}
      </svg>
      <span
        aria-hidden
        className="absolute inset-0 flex items-center justify-center text-lg font-extrabold tabular-nums"
      >
        {score ?? "–"}
      </span>
    </div>
  );
}
