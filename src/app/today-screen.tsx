"use client";

import Link from "next/link";
import { useRouter } from "next/navigation";
import { useEffect, useRef, useState } from "react";
import { AskGainpath } from "@/components/ask-gainpath";
import { ExerciseSummary } from "@/components/exercise-summary";
import { Badge } from "@/components/forms";
import { Button, Notice, Section } from "@/components/ui";
import { WhySheet } from "@/components/why-sheet";
import { getProfile } from "@/data/actions";
import { getDB } from "@/data/db";
import { endDeloadWeek, generateSession, readLive, startDeloadWeek } from "@/data/sessions";
import { explain } from "@/engine/explain";
import { useProfile } from "@/hooks/use-data";
import { useTodaySession, useTrainingContext } from "@/hooks/use-training";
import { useAiStatus } from "@/lib/ai-client";
import { CheckinCard } from "./checkin-card";

export function TodayScreen() {
  const profile = useProfile();
  const router = useRouter();
  const ctx = useTrainingContext();
  const session = useTodaySession();
  const [why, setWhy] = useState(false);
  const [asking, setAsking] = useState(false);
  const ai = useAiStatus();
  const [skipCheckin, setSkipCheckin] = useState(false);
  const [busy, setBusy] = useState(false);
  const [dismissedDeload, setDismissedDeload] = useState(false);
  const autoGenerated = useRef(false);

  useEffect(() => {
    if (profile !== null) return;
    // Next keeps visited routes alive (Activity), so `profile` may be stale from an
    // earlier visit; confirm against the database before redirecting.
    let cancelled = false;
    void getProfile().then((fresh) => {
      if (!fresh && !cancelled) router.replace("/onboarding");
    });
    return () => {
      cancelled = true;
    };
  }, [profile, router]);

  const checkedIn = ctx?.hasCheckin || skipCheckin;
  // Build today's session as soon as the check-in is done (or skipped).
  useEffect(() => {
    if (!ctx || session !== null || !checkedIn || autoGenerated.current) return;
    autoGenerated.current = true;
    void generateSession(getDB());
  }, [ctx, session, checkedIn]);

  if (profile === undefined || ctx === undefined || session === undefined) {
    return <p className="text-zinc-400">Loading…</p>;
  }
  if (!profile || !ctx) {
    return (
      <div className="flex flex-col gap-4">
        <h1 className="text-2xl font-bold">Today</h1>
        <Notice>Register your gym to get a session.</Notice>
        <Link
          href="/gym"
          className="flex min-h-12 items-center justify-center rounded-xl bg-lime-400 font-semibold text-zinc-950"
        >
          My gym
        </Link>
      </div>
    );
  }

  const live = session ? readLive(session) : null;
  const regenerate = async () => {
    setBusy(true);
    await generateSession(getDB());
    setBusy(false);
  };
  const { readiness, deload } = ctx;
  const band = { normal: "good", reduced: "warn", low: "bad" } as const;

  return (
    <div className="flex flex-col gap-4">
      <div className="flex items-baseline justify-between">
        <h1 className="text-2xl font-bold">Today</h1>
        <span className="text-sm text-zinc-500">
          {new Date().toLocaleDateString(undefined, {
            weekday: "long",
            day: "numeric",
            month: "short",
          })}
        </span>
      </div>

      {!checkedIn && (
        <>
          <CheckinCard onDone={() => (autoGenerated.current = false)} />
          <button
            type="button"
            className="min-h-10 text-sm text-zinc-400 underline"
            onClick={() => setSkipCheckin(true)}
          >
            Skip check-in today
          </button>
        </>
      )}

      {checkedIn && (
        <Section title="Readiness">
          <div className="flex items-center gap-3">
            <span className="text-4xl font-bold tabular-nums">{readiness.score}</span>
            <Badge tone={band[readiness.band]}>
              {readiness.band === "normal"
                ? "Ready"
                : readiness.band === "reduced"
                  ? "A bit flat"
                  : "Take it easier"}
            </Badge>
          </div>
          {readiness.rationale.map((r) => (
            <p key={r.rule} className="text-sm text-zinc-400">
              {explain(r)}
            </p>
          ))}
        </Section>
      )}

      {deload.active ? (
        <Notice>
          Lighter week in progress: same exercises, fewer sets, more in reserve (DELOAD-2).{" "}
          <button type="button" className="underline" onClick={() => void endDeloadWeek(getDB())}>
            End early
          </button>
        </Notice>
      ) : (
        (deload.check.trigger || deload.check.reminder) &&
        !dismissedDeload && (
          <Section title={deload.check.trigger ? "A lighter week may help" : "Lighter week?"}>
            {deload.check.rationale.map((r) => (
              <p key={r.rule} className="text-sm text-zinc-300">
                {explain(r)}
              </p>
            ))}
            <p className="text-xs text-zinc-500">
              A deload reduces sets and effort but keeps you training: a full week off isn&apos;t
              better (DELOAD-2).
            </p>
            <div className="flex gap-2">
              <Button
                variant="primary"
                onClick={async () => {
                  await startDeloadWeek(getDB());
                  if (!live?.startedAt) await regenerate();
                }}
              >
                Start lighter week
              </Button>
              <Button onClick={() => setDismissedDeload(true)}>Not now</Button>
            </div>
          </Section>
        )
      )}

      {checkedIn && !live && (
        <Section title="Today's session">
          <p className="text-sm text-zinc-400">Building your session…</p>
          <Button variant="primary" disabled={busy} onClick={regenerate}>
            Build session
          </Button>
        </Section>
      )}

      {live && session && (
        <Section
          title={
            session.status === "done"
              ? "Done for today"
              : live.meta.isDeload
                ? "Today's session (lighter)"
                : "Today's session"
          }
          description={`${live.exercises.filter((e) => e.status !== "swapped_out").length} exercises · ${ctx.gym.name}`}
        >
          {live.exercises.length === 0 && (
            <Notice>Nothing to program: register equipment with linked exercises in My gym.</Notice>
          )}
          <ul className="flex flex-col gap-3">
            {live.exercises
              .filter((e) => e.status !== "swapped_out")
              .map((e) => (
                <li
                  key={`${e.exerciseId}-${e.replaces ?? ""}`}
                  className="rounded-xl border border-zinc-800 bg-zinc-950 p-3"
                >
                  <ExerciseSummary
                    e={e}
                    exercise={ctx.catalog.get(e.exerciseId)}
                    equipment={ctx.equipmentById}
                  />
                </li>
              ))}
          </ul>
          <button
            type="button"
            className="min-h-10 text-left text-sm text-lime-400"
            onClick={() => setWhy(true)}
          >
            Why does today look like this?
          </button>
          {session.status !== "done" && live.exercises.length > 0 && (
            <Link
              href="/session"
              className="flex min-h-14 items-center justify-center rounded-xl bg-lime-400 text-lg font-semibold text-zinc-950"
            >
              {session.status === "active" ? "Continue session" : "Start session"}
            </Link>
          )}
          {session.status === "planned" && (
            <Button disabled={busy} onClick={regenerate}>
              Rebuild session
            </Button>
          )}
        </Section>
      )}

      {ai?.enabled && <Button onClick={() => setAsking(true)}>Ask Gainpath</Button>}

      {why && live && <WhySheet live={live} catalog={ctx.catalog} onClose={() => setWhy(false)} />}
      {asking && <AskGainpath onClose={() => setAsking(false)} />}
    </div>
  );
}
